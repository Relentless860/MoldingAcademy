function startLesson(lessonName) {

    if (lessonName === "Machine Basics") {
        window.location.href = "lessons/machine-basics.html";
    }

    else if (lessonName === "Processing Parameters") {
        window.location.href = "lessons/processing-parameters.html";
    }

    else if (lessonName === "Troubleshooting") {
        window.location.href = "lessons/troubleshooting.html";
    }

    else if (lessonName === "Quiz") {
        window.location.href = "lessons/troubleshooting-quiz.html";
    }

}